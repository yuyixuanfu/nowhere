def tag_entry(key: str, value: str) -> list[str]:
    """Return list of tags for a given entry key + value."""
    text = key + value
    tags = []
    for tag_name, keywords in RULES.items():
        for kw in keywords:
            if kw in text:
                tags.append(tag_name)
                break
    return tags if tags else ["杂物"]


def main():
    with open(INPUT, "r", encoding="utf-8") as f:
        kb = json.load(f)

    labels = {}
    for key, value in kb.items():
        labels[key] = tag_entry(key, value)

    with open(OUTPUT, "w", encoding="utf-8") as f:
        json.dump(labels, f, ensure_ascii=False, indent=2)

    # Write stats
    with open("_tag_stats.txt", "w", encoding="utf-8") as out:
        out.write(f"Total entries: {len(labels)}\n\n")

        counter = Counter()
        for tags in labels.values():
            for t in tags:
                counter[t] += 1

        out.write("Tag distribution:\n")
        for tag, count in counter.most_common():
            out.write(f"  {tag}: {count}\n")

        multi = sum(1 for v in labels.values() if len(v) > 1)
        out.write(f"\nEntries with multiple tags: {multi}\n")

        misc = [k for k, v in labels.items() if v == ["杂物"]]
        out.write(f"\n杂物 count: {len(misc)}\n")
        out.write("杂物 samples:\n")
        for m in misc[:50]:
            val = kb.get(m, "")[:80]
            out.write(f"  {m} || {val}\n")

    print(f"Wrote {len(labels)} entries to {OUTPUT}")
    print(f"杂物 count: {len(misc)}")
    print("Stats written to _tag_stats.txt")


if __name__ == "__main__":
    main()
